// Package main содержит мультианализатор staticlint для статического анализа кода проекта go-metrics.
//
// # Описание
//
// Staticlint - это инструмент статического анализа, объединяющий несколько категорий анализаторов:
// стандартные анализаторы из golang.org/x/tools, анализаторы staticcheck, публичные анализаторы
// и собственный кастомный анализатор.
//
// # Запуск
//
// Для запуска анализа всего проекта выполните:
//
//	go run ./cmd/staticlint ./...
//
// Для анализа конкретного пакета:
//
//	go run ./cmd/staticlint ./internal/handler
//
// Для получения справки по доступным флагам:
//
//	go run ./cmd/staticlint -help
//
// # Включённые анализаторы
//
// ## Стандартные анализаторы (golang.org/x/tools/go/analysis/passes)
//
// - appends - проверяет корректность использования встроенной функции append
// - asmdecl - проверяет соответствие между объявлениями на Go и ассемблерными файлами
// - assign - обнаруживает бесполезные присваивания
// - atomic - проверяет распространённые ошибки при использовании пакета sync/atomic
// - bools - обнаруживает распространённые ошибки с булевыми операторами
// - buildtag - проверяет корректность build tag директив
// - cgocall - обнаруживает нарушения правил передачи указателей в cgo
// - composite - проверяет составные литералы без ключей
// - copylock - проверяет блокировки, передаваемые по значению
// - defers - проверяет распространённые ошибки в отложенных вызовах
// - directive - проверяет известные комментарии-директивы
// - errorsas - проверяет правильность использования errors.As
// - httpresponse - проверяет ошибки при использовании HTTP ответов
// - ifaceassert - обнаруживает невозможные утверждения типов
// - loopclosure - проверяет ссылки на переменные цикла из вложенных функций
// - lostcancel - проверяет, что функции отмены контекста вызываются
// - nilfunc - проверяет бесполезные сравнения функций с nil
// - printf - проверяет согласованность строк формата Printf и аргументов
// - shadow - проверяет переменные, которые могут быть непреднамеренно затенены
// - shift - проверяет сдвиги, которые превышают или равны ширине целого числа
// - sigchanyzer - проверяет небуферизованные каналы сигналов os.Signal
// - sortslice - проверяет вызовы sort.Slice, которые не используют правильный тип для аргумента slice
// - stdmethods - проверяет сигнатуры известных интерфейсных методов
// - stringintconv - проверяет преобразования типов из целых чисел в строки
// - structtag - проверяет правильность тегов структур
// - testinggoroutine - проверяет вызовы (*testing.T).Fatal из горутин, созданных тестом
// - tests - проверяет распространённые ошибки в тестах
// - timeformat - проверяет использование time.Format или time.Parse с неверными макетами
// - unmarshal - проверяет передачу неуказательных или неинтерфейсных значений в unmarshal
// - unreachable - проверяет недостижимый код
// - unsafeptr - проверяет недопустимые преобразования uintptr в unsafe.Pointer
// - unusedresult - проверяет неиспользуемые результаты вызовов некоторых функций
//
// ## Анализаторы staticcheck
//
// ### Класс SA (staticcheck.io) - обнаружение багов и потенциальных проблем
//
// Включены все анализаторы класса SA, которые обнаруживают:
// - некорректное использование стандартной библиотеки
// - проблемы с конкурентностью (race conditions, deadlocks)
// - использование устаревших API
// - некорректные регулярные выражения
// - проблемы с производительностью
// - потенциальные nil pointer dereference
// - и многое другое
//
// Полный список: SA1000-SA1030, SA2000-SA2003, SA3000-SA3001, SA4000-SA4031,
// SA5000-SA5012, SA6000-SA6006, SA9000-SA9009
//
// ### Класс S (simple) - упрощение кода
//
// Анализаторы, предлагающие упрощения кода:
// - удаление избыточных операций
// - упрощение булевых выражений
// - использование более идиоматичных конструкций Go
// - оптимизация строковых операций
//
// Пример: S1000-S1043
//
// ### Класс ST (stylecheck) - соблюдение стиля кода
//
// Анализаторы для проверки стиля кодирования:
// - форматирование комментариев
// - правильное именование (идентификаторы, константы)
// - идиоматичное использование Go конструкций
// - правильное использование godoc комментариев
//
// Пример: ST1000-ST1023
//
// ### Класс QF (quickfix) - быстрые исправления
//
// Анализаторы, предлагающие автоматические исправления для распространённых проблем.
//
// ## Публичные анализаторы
//
// ### bodyclose (github.com/timakin/bodyclose)
//
// Проверяет, что тело HTTP ответов (http.Response.Body) закрывается корректно.
// Незакрытые тела ответов могут привести к утечкам ресурсов и исчерпанию файловых дескрипторов.
//
// Пример проблемного кода:
//
//	resp, err := http.Get(url)
//	if err != nil {
//	    return err
//	}
//	// Отсутствует resp.Body.Close() - утечка ресурсов!
//	data, _ := io.ReadAll(resp.Body)
//
// Правильный код:
//
//	resp, err := http.Get(url)
//	if err != nil {
//	    return err
//	}
//	defer resp.Body.Close()
//	data, _ := io.ReadAll(resp.Body)
//
// ### nilerr (github.com/gostaticanalysis/nilerr)
//
// Обнаруживает ситуации, когда функция возвращает nil вместо ошибки после проверки на ошибку.
// Это распространённая ошибка, которая может скрывать реальные проблемы.
//
// Пример проблемного кода:
//
//	func process() error {
//	    err := doSomething()
//	    if err != nil {
//	        log.Println(err)
//	        return nil  // Должна возвращаться ошибка err!
//	    }
//	    return nil
//	}
//
// ## Кастомные анализаторы
//
// ### osexit - запрет os.Exit в функции main
//
// Запрещает использование прямого вызова os.Exit в функции main пакета main.
//
// Обоснование:
//
// Прямой вызов os.Exit в функции main имеет несколько проблем:
//
// 1. Отложенные вызовы (defer) не выполняются при вызове os.Exit,
// что может привести к неосвобожденным ресурсам, незаписанным буферам и т.д.
//
// 2. Затрудняется тестирование - невозможно протестировать функцию main,
// которая вызывает os.Exit.
//
// 3. Усложняется graceful shutdown - приложение завершается немедленно
// без корректного завершения работы компонентов.
//
// Рекомендуемый подход:
//
// Вместо прямого вызова os.Exit в main, следует:
//
// 1. Выносить основную логику в отдельную функцию (например, run()),
// которая возвращает ошибку или код возврата.
//
// 2. В функции main вызывать эту функцию и обрабатывать результат
// через log.Fatal (который внутренне вызывает os.Exit, но не напрямую)
// или fmt.Fprintf + os.Exit.
//
// Пример правильного кода:
//
//	func main() {
//	    if err := run(); err != nil {
//	        log.Fatal(err)
//	    }
//	}
//
//	func run() error {
//	    app, err := initApp()
//	    if err != nil {
//	        return fmt.Errorf("инициализация: %w", err)
//	    }
//	    defer app.Close()
//
//	    return app.Start()
//	}
//
// # Интеграция в CI/CD
//
// Для интеграции в процесс непрерывной интеграции добавьте в ваш CI скрипт:
//
//	go run ./cmd/staticlint ./...
//
// Анализатор завершится с ненулевым кодом возврата при обнаружении проблем.
//

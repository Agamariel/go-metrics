package audit

import "context"

// Observer определяет интерфейс наблюдателя в паттерне Observer.
//
// Реализации должны быть потокобезопасными, так как Notify может вызываться
// из нескольких горутин одновременно.
//
// Встроенные реализации:
//   - FileObserver: записывает события в файл
//   - HTTPObserver: отправляет события по HTTP
type Observer interface {
	// Notify обрабатывает событие аудита.
	//
	// Метод вызывается асинхронно из Publisher.NotifyAll.
	// При ошибке Publisher логирует её, но продолжает уведомлять других наблюдателей.
	//
	// Реализации должны учитывать контекст для корректной отмены длительных операций.
	Notify(ctx context.Context, event Event) error
}
